export const FONT_5X8: BitmapFont = { w: FONT_W, h: FONT_H, advance: FONT_ADVANCE, first: FONT_FIRST, glyphs: GLYPHS };

export function textWidth(text: string, font: BitmapFont = FONT_5X8): number {
  return text.length ? text.length * font.advance - 1 : 0;
}

/** Draw `text` with its top-left at (x, y). Unknown characters render as '?'. */
export function drawText(b: Bitmap, x: number, y: number, text: string, v = 255, font: BitmapFont = FONT_5X8): void {
  for (let i = 0; i < text.length; i++) {
    let code = text.charCodeAt(i) - font.first;
    if (code < 0 || code >= font.glyphs.length) code = 63 - font.first;
    const glyph = font.glyphs[code];
    const gx = x + i * font.advance;
    for (let row = 0; row < font.h; row++) {
      const py = y + row;
      if (py < 0 || py >= b.height) continue;
      const mask = glyph[row];
      for (let col = 0; col < font.w; col++) {
        if (!(mask & (1 << (font.w - 1 - col)))) continue;
        const px = gx + col;
        if (px >= 0 && px < b.width) b.data[py * b.width + px] = v;
      }
    }
  }
}
